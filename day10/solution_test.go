package main

import "testing"

func TestSolve(t *testing.T) {
	input := `[.##.] (3) (1,3) (2) (2,3) (0,2) (0,1) {3,5,4,7}
[...#.] (0,2,3,4) (2,3) (0,4) (0,1,2) (1,2,3,4) {7,5,12,7,2}
[.###.#] (0,1,2,3,4) (0,3,4) (0,1,2,4,5) (1,2) {10,11,11,5,10,5}`
	p1, p2 := Solve(input)
	if p1 != 7 || p2 != 33 {
		t.Fatalf("Solve() = (%d, %d), want (7, 33)", p1, p2)
	}
}
